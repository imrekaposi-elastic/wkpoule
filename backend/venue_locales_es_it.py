def merge_into_venues(venues: list[dict]) -> None:
    """Add review_es, review_it, accessibility_es, accessibility_it to each venue dict by name."""
    for venue in venues:
        loc = VENUE_LOCALES_ES_IT.get(venue.get("name"))
        if loc is None:
            continue
        venue["review_es"] = loc["review_es"]
        venue["review_it"] = loc["review_it"]
        venue["accessibility_es"] = loc["accessibility_es"]
        venue["accessibility_it"] = loc["accessibility_it"]
