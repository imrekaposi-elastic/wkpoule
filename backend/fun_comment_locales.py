def _apply_pairs(text: str, pairs: list[tuple[str, str]]) -> str:
    out = text
    for src, dst in pairs:
        if src and src in out:
            out = out.replace(src, dst)
    return out


def derive_spanish_from_portuguese(text: str) -> str:
    """Spanish commentary derived from the Portuguese seed (same tone, readable ES)."""
    return _apply_pairs(text, _PT_ES)


def derive_italian_from_english(text: str) -> str:
    """Italian text from English (fallback)."""
    return _apply_pairs(text, _EN_IT)


def derive_italian_from_spanish(text: str) -> str:
    """Italian commentary derived from Spanish (readable IT, same tone as ES)."""
    return _apply_pairs(text, _ES_IT)


def locales_for_comment_bundle(bundle: dict[str, str]) -> tuple[str, str]:
    """Return (italian, spanish) texts for a MATCH_COMMENTS / template entry."""
    en = bundle.get("en") or ""
    it = bundle.get("it") or derive_italian_from_english(en)
    es = bundle.get("es") or derive_spanish_from_portuguese(bundle.get("pt") or en)
    return it, es
